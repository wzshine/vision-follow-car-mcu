#ifndef STEER_CAN_H
#define STEER_CAN_H

#include <stdint.h>

/*
 * 转向 CAN 契约 —— DlaBoard_B(控制板) <-> FOC_steer(转向执行器)。
 *
 * ! **为什么另开一个头文件，而不是加进 foc_can.h：**
 *   foc_can.h 是**驱动**契约(0x210/0x211/0x212/0x213/0x214)，
 *   参与方是控制板和 FOC_Double_C。转向是另一对参与方、另一套帧。
 *   两套无关的契约住进同一个头文件，下一次就是"改 A 撞了 B" ——
 *   而 2026-08-28 那几天 foc_can.h 上同时有两个 session 在动，
 *   正是不该再往里塞第三方东西的时候。
 *
 * ! 字段定义的来源是 FOC_steer 的 App/Src/app_can.c
 *   (handle_steer_cmd / steer_send_status)，由那一侧的 session 于
 *   2026-08-28 提供。本文件是**控制板侧的权威副本**：与那边实现冲突时
 *   要当场对齐，不要各改各的 —— CAN 的字节位置是两块板共有的，
 *   判据是**两边的头文件有没有一起改**。
 *
 * ! ⏳ **截至 2026-08-28 全部未上板验证。** 控制板这一侧一个字段都还没解析,
 *   转向板那一侧也没挂上总线。上板通过后请把这一条删掉,
 *   一个永远挂着的"待验证"标记会变成背景。
 *
 * ! ⚠⚠ 挂上总线之前先读 CONTRACT_CAN_控制板 §6：在 0x210 的接收去留
 *   定下来之前，不要把 FOC_steer 挂上整车总线。
 */

/* ---------------------------------------------------------------------------
 * 0x230  转向指令   控制板 -> 转向板
 *
 * ⚠⚠ **必须周期发，20 ms。不是事件驱动。**
 *
 *   转向板的"300 ms 无刷新即停"不是可以关掉的选项 —— 它是链路失效的
 *   唯一判据。而控制板对旧的第三方伺服是**事件驱动**的(目标变化超过
 *   300/500 计数才发一帧)，于是**目标不变时链路每 300 ms 被判死一次**。
 *   ⇒ 这条和本工程对 0x210 已经写下的规矩是同一条：
 *     **帧本身永不停发，帧的内容才是安全状态。**
 * ------------------------------------------------------------------------- */
#define STEER_CAN_CMD_ID          0x230U
#define STEER_CAN_CMD_PERIOD_MS   20U
#define STEER_CAN_CMD_TIMEOUT_MS  300U   /* 对端默认；[5] 可覆盖 */

/*
 * [0:1] i16 LE 目标。默认单位 **‰**(-1000..+1000)；flags b1 置位时为 mm x10。
 *       ! 用 ‰ 是 2026-08-28 定的：齿条行程是转向板的事实，
 *         司机想打多少度是控制板的事实，‰ 无量纲，正好是两者的交界。
 *         **"角度 -> ‰" 那次换算住在控制板**，只有一个家。
 * [2]   flags，见下
 * [3]   限速 0..255 = 配置上限的 0..100%；0 = 用配置默认
 * [4]   seq，每帧自增(0x231[7] 回显)
 * [5]   超时 x10 ms，0 = 用配置默认(300 ms)
 * [6:7] 保留，发 0
 */
/*
 * b0 使能 —— **每帧电平生效**，由控制板持有。
 *
 * ⚠⚠ **整车使能开关(PD10)断开时，本位必须清零。**
 *
 *   这是 2026-08-28 定下"FOC_steer 不接收 0x210"(方案 A)的**必要条件**。
 *   转向板不再从 0x210 得到任何整车级信息 ⇒ 整车撤防这件事只能由控制板
 *   镜像进这一位。没有它，撤防之后转向板不知情，**仍然按最后一个目标
 *   把齿条按住 —— 一台已经撤防的车，方向机还在使劲**。
 *   ⇒ 而 0x210 和 0x230 的发送方是同一个(本板)，所以不需要第二条总线路径。
 *
 * ⚠⚠ **但不要把 brake 也镜像进来。** FOC_steer session 最初提的条件是
 *   "allow_drive=0 **或** brake=1 时清零"，后半句是错的：
 *   本板的 foc_brake 由 force_brake 置位，而那里面**包含刹车踏板开关**。
 *   ⇒ 照那样做，**司机在弯中踩一脚刹车，转向就失电**。
 *   brake 的含义是"把刹车抱上"，不是"这台车被撤防了"。
 *   **拿一个字段当它不表示的意思用**，是本工程反复付过代价的那一类错。
 *   ⇒ 只镜像 allow_drive(在本板上它恒等于 PD10)。
 *
 * ⚠⚠ 而那个条件错得比"后半句不对"更深（由规格书 session 指出）：
 *
 *   本板的 force_brake 里**第二项就是 (vehicle_enabled == 0)**，
 *   而 allow_drive = (vehicle_enabled != 0)
 *   ⇒ **allow_drive == 0 蕴含 brake == 1**。
 *
 *   ∴ "allow_drive==0 || brake==1" 恰恰**等价于 "brake==1"**。
 *   那个"或"不是两个条件的并集 —— **它把唯一对的那一半删掉了**，
 *   而宽出来的部分恰好是踏板、P 挡、遥控丢失、遥控刹车。
 *
 *   ⇒ **A || B 在 A ⇒ B 时不是"更周全"，是把 A 删掉了**，
 *     而这在读的时候几乎不可见 —— 它长得像"我多考虑了一种情况"。
 *
 *   ⇒ 它和"拿一个字段当它不表示的意思用"是邻居，但机制不同：
 *     **这次字段没有被误解，是布尔式自己塌了。**
 *
 * ⚠⚠ **这条镜像不要靠断言去守，要让它写不出来。**
 *
 *   FOC_steer session 2026-08-28 指出：删掉 0x210 之后，转向板**没有第二个
 *   源可以校验这一位** —— 镜像一旦漂移，它只会看到"仍然使能"，察觉不到。
 *   ⇒ 于是 A 方案的安全性就挂在一句**不会失败的承诺**上，
 *     而不会失败的承诺，和不会红的断言，是同一种东西。
 *
 *   ⇒ 因此实现 0x230 发送时，**b0 必须由发送函数自己从
 *     ServoCAN_t.actuation_allowed 推导出来，不得作为参数传入**。
 *     调用方**根本不提供这一位**，也就没有传错的可能。
 *     **能让它表达不出来，就不要退而用断言去检查它** ——
 *     断言检查的是某一个调用点，推导取消的是**所有**调用点犯错的能力。
 *
 *   ⇒ 同一个 actuation_allowed 也喂着 may_actuate()，两条路径不可能分叉。
 *   ⚠ 今天还没有 0x230 发送路径 ⇒ **这条约束现在没有任何代码在守**，
 *     它是写给实现那一版的人看的(很可能是几个月后的我)。
 *
 * ! 这一位和 servo_can.c 里 may_actuate() 的闸是**同一个互锁的两种表达**：
 *   一个挡住旧的第三方伺服路径，一个通过新的 0x230 告诉 FOC_steer。
 *   两者都由 vehicle_enabled 喂。改一处要想到另一处。
 */
#define STEER_CMD_F_ENABLE        (1U << 0)
#define STEER_CMD_F_UNIT_MM       (1U << 1)   /* 置位 ⇒ [0:1] 是 mm x10 */
#define STEER_CMD_F_RECENTER      (1U << 2)   /* 置位 ⇒ 忽略 [0:1] */
/*
 * ⚠⚠ 清故障按**这一位自己的上升沿**触发，不是电平。
 *
 *   ⇒ 本板要发它时必须**举一帧、然后放下**，绝不能常置。
 *
 * ⚠⚠ **举着这一位期间轴不会上电**（接收侧 `g_steer_enabled = !clr && enable`）。
 *   ⇒ 恢复序列是两帧：`b3=1,b0=0` → 下一帧 `b3=0,b0=1`。
 *   ⚠ **一帧里同时带 b3 和 b0 是无效的** —— 轴不会动，
 *     而且**不会有任何错误提示**。
 *
 * ! 这里原本写的是"按 [4] 序列号的边沿触发"，那是照 FOC_steer 一个
 *   **不成立**的实现写的（2026-08-28 由那侧发现并更正）：
 *   **seq 按本契约每帧自增**，所以"seq 变了"每 20 ms 都为真 ⇒
 *   那个边沿检测等于电平，它声称要防的"常置就每帧清一次故障"
 *   **一点都没防住**。接收侧已改成盯这一位自己。
 *
 *   ⇒ **一个边沿检测器的好坏，取决于它盯着的那个量。**
 *     **盯着一个按设计就会前进的计数器，就是在盯一个电平。**
 *
 *   ⚠ 这一段务必留着：「按 seq 边沿」听起来很合理，
 *     删掉理由，下一个人会把它改回去。
 */
#define STEER_CMD_F_CLR_FAULT     (1U << 3)   /* 边沿触发，不是电平 */

/* ---------------------------------------------------------------------------
 * 0x231  转向状态   转向板 -> 控制板，20 ms
 *
 * [0:1] i16 LE 位置 ‰
 * [2:3] i16 LE 位置 mm x10
 * [4]   状态位，见下
 * [5]   steer_fault_t：0=无 1=未标定 2=传感器 3=跳变 4=越程 5=方向
 * [6]   i8 iq x10(电机出力，可用来看路面负载/卡阻)
 * [7]   回显 0x230[4] 的 seq
 * ------------------------------------------------------------------------- */
#define STEER_CAN_STATUS_ID       0x231U
#define STEER_CAN_STATUS_PERIOD_MS 20U

#define STEER_ST_CALIBRATED       (1U << 0)
#define STEER_ST_ENABLED          (1U << 1)
#define STEER_ST_ON_POSITION      (1U << 2)
#define STEER_ST_LIMIT_NEG        (1U << 3)
#define STEER_ST_LIMIT_POS        (1U << 4)
#define STEER_ST_FAULT            (1U << 5)   /* 轴故障，码在 [5] */
#define STEER_ST_ASSIST           (1U << 6)
/*
 * ⚠⚠ b7 —— 驱动侧已锁存故障。2026-08-28 由 FOC_steer session 加入。
 *
 *   **为什么必须和 b5 分开**：[5] 发的是 steer_fault_t，**里面根本没有
 *   "桥跳闸了"这个取值** —— 过流、DRV nFAULT、欠压、过压住在另一个变量里,
 *   从来不进这一帧。
 *   ⇒ 一次锁存的过流之后，0x231 的**每个字段看起来都健康**：
 *     故障位 0、故障码 0、位置照常上报(传感器好好的，是电机停了)。
 *     **收到的是一帧完全正常的状态帧，而齿条根本不会动。**
 *
 *   b5 = 轴不信任自己的位置；b7 = 桥关了、齿条根本不会动。
 *   **两种失效，两种应对**，不能合成一位。
 *
 * ! **b7 是一位汇总**：过流 / DRV nFAULT / 欠压 / 过压 / 电流测量不可信,
 *   任一锁存即置位。它说的是"桥关了、齿条不会动"，**不说是哪一种**;
 *   [5] 里也没有对应取值 ⇒ **两者不可互相推导**，细节走串口。
 *   ⇒ 又一次：**这一位能回答的问题比它听起来的小。**
 */
#define STEER_ST_DRV_FAULT        (1U << 7)

/*
 * ⚠ [5] 的故障码集合以后会增加。**未知码一律按"有故障"处理，
 *   不得按"无故障"处理。**
 *
 *   理由和 0x212[5:6] 的 0 有两个意思是同一条：**`0 = 无故障` 和
 *   `0 = 我不知道` 在一个字节里同形** —— 旧固件、没实现的字段、
 *   丢帧后的初值全都给 0。
 *   ⇒ **判据看 [4] 的 b5/b7 两位，[5] 只用来解释**，不用来判定。
 */
/*
 * ⚠ **0x231 的八个字节已经排满了。** 下一个想加字段的人(可能是几个月后的你或我)：
 *   **这里没有空位，要加就得开新帧**，别花半天去找。
 *   0x232 起未占用；⚠ 不要用 0x213/0x214(拓扑 B 的右轮板)。
 */
#define STEER_FAULT_NONE          0U
#define STEER_FAULT_UNCAL         1U
#define STEER_FAULT_SENSOR        2U
#define STEER_FAULT_JUMP          3U
#define STEER_FAULT_OVERTRAVEL    4U
#define STEER_FAULT_DIR           5U

#endif
