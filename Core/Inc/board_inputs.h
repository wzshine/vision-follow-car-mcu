#ifndef BOARD_INPUTS_H
#define BOARD_INPUTS_H

#include "stm32f4xx_hal.h"

/*
 * 工作模式（手动 / 遥控 / 训练 / 跟随）：
 * 仅以串口屏变量为准——屏通过 0x05A1 地址上报键值（见 screen.h 中 SCREEN_ADDR_MODE、SCREEN_KEY_MODE_*），
 * 主循环按 key_addr 切换 g_steering_mode。无单独「模式」GPIO。
 */

/* ===================== PRND 档位开关：接线标准 =====================
 *
 * ⚠⚠ **本节是接线的权威定义。** 2026-08-30 由固件侧定，然后照它接线。
 *
 * 在这之前板上没有任何 PRND 定义：U7 在 EDA 定版说明里只叫
 * "INPUT_PD0/PD1/PD4/PD3"，四个通用数字输入，没有哪个脚属于哪个档的说法。
 * 而固件里那段映射（PD0→R、PD1→D、PD3→P、PD4→P）是**没有依据的**——
 * 没有针脚能产生 N，两个产生 P，而唯一产生 D 的是排在第二位的那个。
 * 源码里分不出那是在补偿某根交叉的线，还是就是个 bug。
 * ⇒ 现在不猜了：定一个标准，让线去迁就它。
 *
 * ---- 连接器（硬件事实，来自当前原理图，不可改） ----
 *
 *   来源：`EDA/DlaBoard_B/hardware/schematic/DlaBoard_B1_Schematic1_2026-08-01.pdf`
 *   第 3 页（control）的 U7（ZX-HY2.0-5PWZ）+ 同页 INPUT 区的 IN1..IN4 网络。
 *
 *   U7，5P，2.0mm。**4/5 脚是交叉的**：
 *
 *     U7 脚位 | 信号 | MCU 引脚
 *        1    | GND  | —
 *        2    | IN1  | PD0
 *        3    | IN2  | PD1
 *        4    | IN4  | PD3     <-- 交叉
 *        5    | IN3  | PD4     <-- 交叉
 *
 *   ⚠⚠ **对外规格书 §8.2 那一行和这个相反**（它写"4=IN3(PD4)、5=IN4(PD3)"）。
 *     按原理图，理由是原理图出自网表、规格书那行是手写的散文。
 *     ⇒ **这条要报给硬件那边订正规格书**（EDA 树只读，本 session 不改它）。
 *     ⚠ 而且这件事**不必靠读图定论**：接好线把 U7 某一脚拉到 GND，
 *       看 `GEAR?` 里哪个括号内的 MCU 引脚变 1，当场就有答案。
 *
 *   ⚠ 2026-08-30 我第一版按规格书写反了，原因是去读了固件仓
 *     `shcematicl/` 里 **2026-06-01 的旧 PNG**（比定版图早两个月）。
 *     ⇒ 查硬件事实要去 `EDA/DlaBoard_B/hardware/schematic/` 拿**日期最新**的那份。
 *
 * ---- 档位分配（固件定义，接线照此） ----
 *
 *     U7 脚位 | 档位
 *        1    | GND（选挡开关的公共端接这里）
 *        2    | P
 *        3    | R
 *        4    | N
 *        5    | D
 *
 *   ⭐ 按 U7 的**物理脚位顺序**排成 P-R-N-D —— 也就是排挡杆上印的那个顺序。
 *      接线的人按顺序插，不用记哪个 MCU 引脚叫什么。
 *      ⇒ 代价是 N 落在 PD3、D 落在 PD4（因为连接器 4/5 脚是交叉的）。
 *        那个别扭属于硬件，藏在这里，不外泄给接线的人。
 *      ⭐ 也正因为标准定在**连接器脚位**上，上面那条规格书/原理图的分歧
 *        真要翻案，改的也只有下面两行宏，**接线标准不动**。
 *
 * ---- 电气 ----
 *
 *   低有效。MCU 内部上拉已开（2026-08-27 补的：Cube 生成的那段把这四个脚
 *   配成了 NOPULL，而头文件一直声称是上拉）。⇒ **没接线的脚稳定读 1。**
 *
 *   选挡开关的公共端接 U7 脚 1（GND）；选中哪个档，就把对应那个脚拉到低。
 *
 * ---- ⚠⚠ 开关类型：必须是"四位置选择开关"，不是四个按钮 ----
 *
 *   **要求：任一时刻，当前档位那一路持续闭合（读 0），其余三路断开（读 1）。**
 *
 *   这一条不是风格问题，它决定了断线时会发生什么：
 *
 *     选择开关（持续闭合）+ 电平解码：线掉了 ⇒ 四路全高 ⇒ 解不出档位
 *       ⇒ 落到 P（刹车）。**故障看得见，而且方向是安全的。**
 *
 *     按钮（瞬时闭合）+ 边沿闩锁：线掉了 ⇒ 没有任何边沿 ⇒ 档位**停在原地**
 *       ⇒ 一台挂着 D 档、没有档位输入、而且没有任何东西发现的车。
 *       ⚠ 那正是这个仓一直在记的那个缺陷形状：**"读不出来"被当成"是安全的"。**
 *
 *
 *   ⇒ 固件按前者实现。接线之后第一件事是拨一遍杆看 `GEAR?`：
 *      它把四路**原始电平**和解出来的档位分开报，一次拨杆就能确认
 *      开关是不是持续闭合型的。
 *
 * ---- 解码规则（实现在 dla_cart_loop.inc，判据写在这里） ----
 *
 *   1. **恰好一路为低** ⇒ 那个档位。
 *   2. **零路为低** ⇒ P，并计数。覆盖：连接器没插、公共端断了、
 *      先断后通(break-before-make)的杆在两档之间扫过。
 *   3. **两路及以上为低** ⇒ P，并计数。覆盖：线短路、
 *      先通后断(make-before-break)的杆在两档之间扫过。
 *      ⚠ **不是"按优先级取一个"** —— 从 P 扫到 D 会路过 R 和 N，
 *        取优先级等于把一次故障读成一次正常换挡。
 *   4. 上面三条的结果要**稳定 GEAR_DEBOUNCE_MS 才生效**，且防抖加在
 *      **解出来的档位**上，不是加在每一路电平上。⇒ 扫杆途中的瞬时
 *      2/3 两种情形被滤掉，不会打出一个刹车脉冲。
 *   5. 开机 GEAR_BOOT_IGNORE_MS 内不解码；在第一次解出有效档位之前，档位是 **P**。
 *
 * ---- ⚠ 和串口屏的关系：三态 ----
 *
 *   屏（0x05E1）也能设档位。两个都在的时候谁说了算？
 *
 *     从没解出过有效档位（U7 没接） ⇒ 允许屏设档。这是接线之前的现状，
 *                                    不能因为定了标准就把它弄坏。
 *     解出过一次有效档位（U7 接了） ⇒ **实体开关说了算，屏不再能设档。**
 *
 *   ⚠ 一个实体排挡杆压过触摸屏，这是安全方向；而"从没见过开关"和
 *     "见过开关但现在读不出来"是两个不同的答案 —— 后者走规则 2，落 P。
 *     ⇒ 这两句话不要合并成"没读到就用屏的"，那会让一根断掉的线
 *       悄悄把控制权交回屏幕。
 */
#define GEAR_SW_GPIO_Port  GPIOD
#define GEAR_P_Pin         GPIO_PIN_0   /* U7 脚 2 (IN1) */
#define GEAR_R_Pin         GPIO_PIN_1   /* U7 脚 3 (IN2) */
#define GEAR_N_Pin         GPIO_PIN_3   /* U7 脚 4 (IN4) ⚠ 是 PD3 —— 4/5 脚交叉 */
#define GEAR_D_Pin         GPIO_PIN_4   /* U7 脚 5 (IN3) ⚠ 是 PD4 —— 4/5 脚交叉 */

/* 档位来源三态。⚠ "从没见过开关"和"见过但现在读不出来"必须分开 —— 见上。 */
#define GEAR_SRC_NONE      0U   /* 从没解出过有效档位：U7 大概没接，屏可以设档 */
#define GEAR_SRC_SWITCH    1U   /* 解出过：实体开关说了算，屏不再能设档 */

/* Vehicle enable input: CN22 / INPUT_PD10. Active low, external pull-up. */
#define VEHICLE_ENABLE_GPIO_Port  GPIOD
#define VEHICLE_ENABLE_Pin        GPIO_PIN_10

#endif
